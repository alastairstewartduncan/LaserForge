using AsdLasercraft.Core.Gcode;
using AsdLasercraft.Core.Generators;
using AsdLasercraft.Core.Geometry;
using AsdLasercraft.Core.Imaging;
using AsdLasercraft.Core.Model;

namespace AsdLasercraft.Core.Tests;

/// <summary>
/// Golden-file tests: generate G-code for fixed projects and compare it line by line with the files in
/// tests/AsdLasercraft.Core.Tests/golden. Any change to the output — intended or not — shows up as a diff.
///
/// Every run writes what it produced to artifacts/golden-actual (uploaded by CI). After an intended change,
/// copy those files over the goldens, or run with UPDATE_GOLDEN=1. A missing golden is reported, not failed,
/// so a new case can be bootstrapped from CI output.
/// </summary>
internal static class GoldenTests
{
    [Test] static void Golden_FillCrossHatchScanOffset()
    {
        var p = Project();
        p.Machine.ScanOffsets.Add(new ScanOffsetPoint(2000, 0.1));
        p.Machine.ScanOffsets.Add(new ScanOffsetPoint(4000, 0.25));
        var layer = MakeLayer(p, LayerMode.Fill, l => { l.SpeedMmMin = 3000; l.PowerPercent = 35; l.LineIntervalMm = 0.5; l.FillAngleDeg = 30; l.CrossHatch = true; l.OverscanMm = 1; });
        Add(p, layer, ShapeFactory.Rectangle(20, 20, 12, 8, cornerRadius: 2));
        Add(p, layer, ShapeFactory.Ellipse(40, 20, 10, 10));
        Check("fill-crosshatch-scanoffset", GcodeGenerator.Generate(p));
    }

    [Test] static void Golden_CutKerfTabs()
    {
        var p = Project();
        var layer = MakeLayer(p, LayerMode.Line, l => { l.SpeedMmMin = 300; l.PowerPercent = 100; l.Passes = 2; l.KerfMm = 0.15; l.TabCount = 3; l.TabWidthMm = 1.5; l.AirAssist = true; });
        Add(p, layer, new VectorShape(new[]
        {
            ShapeFactory.Rectangle(10, 10, 40, 30).Paths[0],
            ShapeFactory.Ellipse(20, 20, 10, 10).Paths[0],
            ShapeFactory.Polygon(35, 18, 10, 12, 6).Paths[0],
        }));
        Add(p, layer, ShapeFactory.Line(new Vec2(60, 10), new Vec2(80, 30)));
        Check("cut-kerf-tabs", GcodeGenerator.Generate(p));
    }

    [Test] static void Golden_RasterGrayscaleCurrentPosition()
    {
        var p = Project();
        p.Job.Origin = JobOrigin.CurrentPosition;
        p.Job.Anchor = JobAnchor.Center;
        var layer = MakeLayer(p, LayerMode.Image, l => { l.SpeedMmMin = 2500; l.PowerPercent = 60; l.MinPowerPercent = 10; l.LineIntervalMm = 0.5; });
        var gray = new byte[16 * 8];
        for (int y = 0; y < 8; y++) for (int x = 0; x < 16; x++) gray[y * 16 + x] = (byte)(x * 16 + (y % 2) * 8);
        Add(p, layer, new ImageShape { Name = "gradient", X = 30, Y = 40, WidthMm = 8, HeightMm = 4, PixelWidth = 16, PixelHeight = 8, Gray = gray, Dither = DitherMode.Grayscale });
        Check("raster-grayscale-current-position", GcodeGenerator.Generate(p));
    }

    [Test] static void Golden_DitheredUserOrigin()
    {
        var p = Project();
        p.Job.Origin = JobOrigin.UserOrigin;
        p.Job.Anchor = JobAnchor.BottomLeft;
        var layer = MakeLayer(p, LayerMode.Image, l => { l.SpeedMmMin = 3000; l.PowerPercent = 45; l.LineIntervalMm = 0.5; });
        var gray = new byte[12 * 12];
        for (int y = 0; y < 12; y++) for (int x = 0; x < 12; x++)
            gray[y * 12 + x] = (byte)Math.Clamp(255 - Math.Sqrt((x - 6) * (x - 6) + (y - 6) * (y - 6)) * 40, 0, 255);
        Add(p, layer, new ImageShape { Name = "dot", X = 50, Y = 50, WidthMm = 6, HeightMm = 6, PixelWidth = 12, PixelHeight = 12, Gray = gray, Dither = DitherMode.Jarvis });
        Check("dithered-user-origin", GcodeGenerator.Generate(p));
    }

    [Test] static void Golden_MaterialTestGrid()
    {
        var p = MaterialTestGenerator.Create(new MachineProfile(), new MaterialTestOptions { SpeedSteps = 2, PowerSteps = 3, CellSizeMm = 5, LineIntervalMm = 0.5 });
        Check("material-test-grid", GcodeGenerator.Generate(p));
    }

    // ------------------------------------------------------------------ helpers

    private static LaserProject Project() => new() { Machine = new MachineProfile { Name = "Golden test laser", BedWidthMm = 200, BedHeightMm = 200 } };

    private static Layer MakeLayer(LaserProject p, LayerMode mode, Action<Layer> configure)
    {
        var l = LaserProject.DefaultLayer(mode);
        l.Name = mode + " layer";
        configure(l);
        p.Layers.Add(l);
        return l;
    }

    private static void Add(LaserProject p, Layer layer, Shape s)
    {
        s.LayerId = layer.Id;
        p.Shapes.Add(s);
    }

    private static void Check(string name, GcodeJob job)
    {
        var text = string.Join("\n", job.Lines.Where(l => !l.StartsWith("; Generated by", StringComparison.Ordinal))) + "\n";
        var root = RepoRoot();
        var actualDir = Path.Combine(root, "artifacts", "golden-actual");
        Directory.CreateDirectory(actualDir);
        File.WriteAllText(Path.Combine(actualDir, name + ".gcode"), text);

        var goldenDir = Path.Combine(root, "tests", "AsdLasercraft.Core.Tests", "golden");
        var goldenPath = Path.Combine(goldenDir, name + ".gcode");
        if (Environment.GetEnvironmentVariable("UPDATE_GOLDEN") == "1")
        {
            Directory.CreateDirectory(goldenDir);
            File.WriteAllText(goldenPath, text);
            return;
        }
        if (!File.Exists(goldenPath))
        {
            Console.WriteLine($"  NOTE  golden file '{name}.gcode' not found; output written to artifacts/golden-actual");
            if (Environment.GetEnvironmentVariable("GITHUB_ACTIONS") == "true")
                Console.WriteLine($"::warning title=Golden file missing::{name}.gcode – push a commit containing [update-golden] to create it");
            return;
        }

        var expected = File.ReadAllText(goldenPath).Replace("\r\n", "\n").Split('\n');
        var actual = text.Split('\n');
        for (int i = 0; i < Math.Max(expected.Length, actual.Length); i++)
        {
            string e = i < expected.Length ? expected[i] : "<end of file>";
            string a = i < actual.Length ? actual[i] : "<end of file>";
            if (e != a) throw new Exception($"{name}.gcode differs at line {i + 1}: expected '{e}' but got '{a}'");
        }
    }

    private static string RepoRoot()
    {
        foreach (var start in new[] { Directory.GetCurrentDirectory(), AppContext.BaseDirectory })
        {
            var dir = new DirectoryInfo(start);
            while (dir != null)
            {
                if (File.Exists(Path.Combine(dir.FullName, "AsdLasercraft.sln"))) return dir.FullName;
                dir = dir.Parent;
            }
        }
        return Directory.GetCurrentDirectory();
    }
}

using System.Globalization;
using System.Text;
using AsdLasercraft.Core.Geometry;
using AsdLasercraft.Core.Model;

namespace AsdLasercraft.Core.Gcode;

/// <summary>One recorded head movement, in project space (Y-down mm). Used by the simulated preview.</summary>
/// <param name="PowerFraction">0 = laser off, 1 = layer power at the machine's maximum S.</param>
/// <param name="LayerIndex">Index of the project layer being burned, or -1 for framing/travel outside a layer.</param>
public readonly record struct JobMove(Vec2 From, Vec2 To, float PowerFraction, bool Rapid,
                                      double StartSeconds, double EndSeconds, int LayerIndex);

/// <summary>
/// How project coordinates map to machine coordinates.
/// Absolute: straight onto the bed. Relative: the anchor point becomes X0 Y0 of the work coordinate system.
/// </summary>
public readonly record struct JobPlacement(JobOrigin Origin, Vec2 Anchor)
{
    public static readonly JobPlacement Absolute = new(JobOrigin.Absolute, Vec2.Zero);
    public bool IsRelative => Origin != JobOrigin.Absolute;
}

/// <summary>
/// Low-level G-code emitter. Takes project-space (Y-down) coordinates, converts to machine space,
/// suppresses repeated modal words (G1, S, F) to keep the stream small, and tracks time/distance.
/// </summary>
public sealed class GcodeWriter
{
    private readonly MachineProfile _m;
    private readonly JobPlacement _placement;
    private readonly List<string> _lines = new();
    private readonly List<JobMove>? _moves;
    private Vec2? _pos;          // current position, project space
    private string? _motion;     // "G0" / "G1"
    private double? _s;
    private double? _f;
    private string? _lastX, _lastY;

    public double CutDistanceMm { get; private set; }
    public double TravelDistanceMm { get; private set; }
    public double EstimatedSeconds { get; private set; }

    /// <summary>Layer index stamped on recorded moves.</summary>
    public int CurrentLayerIndex { get; set; } = -1;

    public IReadOnlyList<string> Lines => _lines;
    public IReadOnlyList<JobMove> Moves => (IReadOnlyList<JobMove>?)_moves ?? Array.Empty<JobMove>();
    public JobPlacement Placement => _placement;

    public GcodeWriter(MachineProfile machine, JobPlacement? placement = null, bool recordMoves = false)
    {
        _m = machine;
        _placement = placement ?? JobPlacement.Absolute;
        if (recordMoves) _moves = new List<JobMove>();
    }

    public void Comment(string text) => _lines.Add("; " + text.Replace('\n', ' '));

    public void Raw(string line) => _lines.Add(line);

    public void Header()
    {
        Comment($"Generated by {AppInfo.ShortName} {AppInfo.Version} on {DateTime.Now:yyyy-MM-dd HH:mm}");
        Comment($"Machine: {_m.Name}, bed {Fmt(_m.BedWidthMm)} x {Fmt(_m.BedHeightMm)} mm, S max {Fmt(_m.MaxSpindleS)}");
        Preamble();
        Raw(_m.DynamicPower ? "M4 S0" : "M3 S0"); // laser enabled at zero power; G1 moves set S
        _s = 0;
    }

    /// <summary>Units, absolute mode and the work-coordinate setup for the chosen origin.</summary>
    public void Preamble()
    {
        Raw("G21");            // millimetres
        Raw("G90");            // absolute
        switch (_placement.Origin)
        {
            case JobOrigin.Absolute:
                Comment("Origin: absolute machine coordinates");
                Raw("G92.1");  // clear any temporary offset left by an interrupted current-position job
                Raw("G54");
                break;
            case JobOrigin.UserOrigin:
                Comment("Origin: user origin (G54) at the job's anchor point");
                Raw("G92.1");
                Raw("G54");
                break;
            case JobOrigin.CurrentPosition:
                Comment("Origin: current head position = job's anchor point");
                Raw("G92 X0 Y0"); // where the head is now becomes the anchor
                break;
        }
        // In relative modes the head starts at the anchor, so remember that as our position for travel accounting.
        if (_placement.IsRelative && _pos == null) _pos = _placement.Anchor;
    }

    public void Footer()
    {
        Raw("M5");
        if (_placement.IsRelative)
        {
            Rapid(_placement.Anchor);                 // back to where we started, ready to run again
            if (_placement.Origin == JobOrigin.CurrentPosition) Raw("G92.1");
        }
        else if (_m.ReturnToOrigin) Raw("G0 X0 Y0");
        Raw("M2");
    }

    /// <summary>Laser-off travel move.</summary>
    public void Rapid(Vec2 p)
    {
        if (_pos is { } cur && Vec2.Distance(cur, p) < 1e-4) return;
        var sb = new StringBuilder();
        if (_motion != "G0") { sb.Append("G0"); _motion = "G0"; }
        AppendXY(sb, p);
        _lines.Add(sb.ToString());
        Account(p, _m.TravelSpeedMmMin, 0, rapid: true);
    }

    /// <summary>Burning (or, with power 0, laser-off at feed rate) linear move.</summary>
    public void Cut(Vec2 p, double powerS, double feedMmMin)
    {
        if (_pos is { } cur && Vec2.Distance(cur, p) < 1e-4) return;
        var sb = new StringBuilder();
        if (_motion != "G1") { sb.Append("G1"); _motion = "G1"; }
        AppendXY(sb, p);
        double s = Math.Round(powerS, 1);
        if (_s != s) { sb.Append(" S").Append(Fmt(s)); _s = s; }
        if (_f != feedMmMin) { sb.Append(" F").Append(Fmt(feedMmMin)); _f = feedMmMin; }
        _lines.Add(sb.ToString());
        Account(p, feedMmMin, s, rapid: false);
    }

    public Vec2? Position => _pos;

    private void Account(Vec2 p, double feed, double s, bool rapid)
    {
        double d = _pos is { } cur ? Vec2.Distance(cur, p) : 0;
        if (s > 0) CutDistanceMm += d; else TravelDistanceMm += d;
        double t0 = EstimatedSeconds;
        if (feed > 0) EstimatedSeconds += d / feed * 60.0;
        if (_moves != null && _pos is { } from)
        {
            float frac = _m.MaxSpindleS > 0 ? (float)Math.Clamp(s / _m.MaxSpindleS, 0, 1) : 0;
            _moves.Add(new JobMove(from, p, frac, rapid, t0, EstimatedSeconds, CurrentLayerIndex));
        }
        _pos = p;
    }

    // Only axes that change are written: raster rows then become "X12.3 S400", roughly halving file size
    // and the number of bytes GRBL has to parse per pixel run.
    private void AppendXY(StringBuilder sb, Vec2 p)
    {
        var mp = ToMachine(p);
        string x = Fmt(mp.X), y = Fmt(mp.Y);
        bool writeX = _lastX != x, writeY = _lastY != y;
        if (!writeX && !writeY) writeX = true;
        if (writeX) { if (sb.Length > 0) sb.Append(' '); sb.Append('X').Append(x); _lastX = x; }
        if (writeY) { if (sb.Length > 0) sb.Append(' '); sb.Append('Y').Append(y); _lastY = y; }
    }

    /// <summary>Project space (Y-down, bed top-left = 0,0) to the coordinates written in the G-code.</summary>
    public Vec2 ToMachine(Vec2 p)
    {
        if (_placement.IsRelative)
        {
            double dx = p.X - _placement.Anchor.X, dy = p.Y - _placement.Anchor.Y;
            return _m.FlipY ? new Vec2(dx, -dy) : new Vec2(dx, dy);
        }
        return _m.FlipY ? new Vec2(p.X, _m.BedHeightMm - p.Y) : p;
    }

    public static string Fmt(double v)
    {
        var s = Math.Round(v, 3).ToString("0.###", CultureInfo.InvariantCulture);
        return s == "-0" ? "0" : s;
    }
}
